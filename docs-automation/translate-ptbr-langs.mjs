import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function loadPtBr() {
  const raw = fs.readFileSync(path.join(__dirname, '_wave10-chunks/pt-br.mjs'), 'utf8');
  return Function(`return (${raw.trim().replace(/^"pt-br":\s*/, '').replace(/,\s*$/, '')})`)();
}

function serialize(obj, indent = 0) {
  const pad = '  '.repeat(indent);
  const padIn = '  '.repeat(indent + 1);
  if (Array.isArray(obj)) {
    if (obj.every((x) => typeof x === 'string'))
      return '[\n' + obj.map((s) => padIn + JSON.stringify(s)).join(',\n') + '\n' + pad + ']';
    return '[\n' + obj.map((v) => padIn + serialize(v, indent + 1)).join(',\n') + '\n' + pad + ']';
  }
  if (obj && typeof obj === 'object') {
    return '{\n' + Object.entries(obj).map(([k, v]) => {
      const key = /^[a-zA-Z_$][\w$-]*$/.test(k) && !k.includes('-') ? k : JSON.stringify(k);
      return padIn + key + ': ' + serialize(v, indent + 1);
    }).join(',\n') + '\n' + pad + '}';
  }
  return JSON.stringify(obj);
}

function translateStr(s, lang) {
  const maps = { nl: PT_NL, de: PT_DE, it: PT_IT, ar: PT_AR, ru: PT_RU };
  const map = maps[lang];
  if (map[s]) return map[s];
  // phrase-level replacements longest first
  let out = s;
  const phrases = Object.entries(map).sort((a, b) => b[0].length - a[0].length);
  for (const [from, to] of phrases) {
    if (from.length > 3) out = out.split(from).join(to);
  }
  return out;
}

function deepTranslate(obj, lang) {
  if (typeof obj === 'string') return translateStr(obj, lang);
  if (Array.isArray(obj)) return obj.map((v) => deepTranslate(v, lang));
  if (obj && typeof obj === 'object') {
    const o = {};
    for (const [k, v] of Object.entries(obj)) o[k] = deepTranslate(v, lang);
    return o;
  }
  return obj;
}

